// Run with NODE_PATH pointing at an external Playwright install. No app dependency.
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const base = process.env.APP_URL || 'http://localhost:8080';
try {
  await page.goto(base);
  await page.waitForSelector('.algorithm-card');
  assert.equal(await page.locator('.algorithm-card').count(), 40);
  for (const theme of ['midnight','paper','plum','lab']) {
    await page.locator('#theme-toggle').click();
    const buttonBox = await page.locator('#theme-toggle').boundingBox();
    const menuBox = await page.locator('#theme-options').boundingBox();
    assert.ok(Math.abs(menuBox.y - (buttonBox.y + buttonBox.height + 8)) < 3, 'Theme menu sits below its button');
    assert.ok(menuBox.x <= buttonBox.x + buttonBox.width && menuBox.x + menuBox.width >= buttonBox.x, 'Theme menu aligns with its button');
    const expectedLeft = Math.max(16, Math.min(buttonBox.x + buttonBox.width - menuBox.width, page.viewportSize().width - menuBox.width - 16));
    assert.ok(Math.abs(menuBox.x - expectedLeft) < 2, 'Theme menu right edge follows button, clamped to viewport');
    await page.locator(`input[name="theme"][value="${theme}"]`).check();
    assert.equal(await page.locator('html').getAttribute('data-theme'), theme);
    await page.reload();
    await page.waitForSelector('.algorithm-card');
    assert.equal(await page.locator('html').getAttribute('data-theme'), theme);
  }
  await page.locator('#algo-search').fill('shortest');
  assert.ok(await page.locator('.algorithm-card:visible').count() > 0);
  await page.getByRole('button', {name: /^Sorting /}).click();
  assert.equal(await page.locator('.algorithm-card:visible').count(), 0);
  await page.locator('#reset-search').click();
  await page.locator('#algo-search').fill('merge');
  await page.locator('#card-merge').click();
  await page.waitForSelector('#workspace:visible');
  assert.match(await page.locator('#viz-title').textContent(), /Merge/);
  await page.locator('#btn-next').click();
  assert.match(await page.locator('#step-counter').textContent(), /Step 2 /);
  await page.locator('#btn-custom-input').click();
  await page.locator('#custom-input-val').fill('{');
  await page.locator('#btn-modal-apply').click();
  assert.equal(await page.locator('#modal-error').isVisible(), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#custom-modal').isVisible(), false);
  await page.locator('#back-library').click();
  assert.equal(await page.locator('#algo-search').inputValue(), 'merge');
  await page.goBack();
  await page.waitForSelector('#workspace:visible');
  await page.locator('#btn-reset').click();
  await page.locator('#btn-play').click();
  await page.waitForTimeout(80);
  await page.locator('#btn-play').click();
  const paused = await page.locator('#step-counter').textContent();
  await page.waitForTimeout(700);
  assert.equal(await page.locator('#step-counter').textContent(), paused, 'Pause must cancel pending frame');
  await page.locator('#tab-doc-btn').focus();
  await page.keyboard.press('Home');
  assert.equal(await page.locator('#tab-code-btn').getAttribute('aria-selected'), 'true');
  await page.keyboard.press('End');
  assert.equal(await page.locator('#tab-doc').isVisible(), true);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({path:'/tmp/opencode/gorithm-workspace.png',fullPage:true});
  await page.goto(base+'#algorithm=missing');
  await page.waitForSelector('#navigation-notice:visible');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('#algo-search').fill('');
  await page.screenshot({path:'/tmp/opencode/gorithm-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'/tmp/opencode/gorithm-desktop.png',fullPage:true});
  assert.deepEqual(errors, []);
  await page.goto(base);
  await page.waitForSelector('.algorithm-card');
  await page.locator('.explore-link').click();
  await page.locator('#card-merge').click();
  await page.goBack();
  assert.equal(await page.locator('#library').isVisible(), true, 'Back to discovery restores library');
  await page.locator('#card-merge').click();
  await page.locator('.skip-link').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workspace').isVisible(), true, 'Skip link preserves lesson');
  await page.locator('#btn-custom-input').click();
  await page.goBack();
  assert.equal(await page.locator('#custom-modal').isVisible(), false, 'Navigation closes dialog');
  const failure = await browser.newPage();
  await failure.route('**/app.wasm', route=>route.abort());
  await failure.goto(base);
  await failure.waitForSelector('#runtime-error:visible');
  console.log('PASS: discovery, navigation, playback, dialog, tabs, responsive layout, runtime failure');
} finally { await browser.close(); }
